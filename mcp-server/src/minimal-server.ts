app.post('/test', (req, res) => {
  res.json({
    message: 'MCP Server test endpoint working',
    request_body: req.body,
    timestamp: new Date().toISOString()
  });
});

// Start server
const PORT = process.env.PORT || 3001;
app.listen(PORT, () => {
  console.log('🚀 Minimal MCP Server Started');
  console.log(`📍 Server URL: http://localhost:${PORT}`);
  console.log(`🔍 Health check: http://localhost:${PORT}/health`);
  console.log(`📋 List tools: POST http://localhost:${PORT}/list-tools`);
  console.log(`⚡ Call tool: POST http://localhost:${PORT}/call-tool`);
  console.log(`🧪 Test endpoint: POST http://localhost:${PORT}/test`);
  console.log('');
  console.log('✨ Ready to process chicken business requests!');
});

export default app;